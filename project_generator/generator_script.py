#!/usr/bin/env python3
"""
Sovereign AI Governance SDK: Project Document Synthesis Generator
Autonomous script that moulds Department Architect protocols into a
project-specific constitutional documentation suite (.project_docs/).
"""

import sys
import os
import json
import argparse
from pathlib import Path
from datetime import datetime, timezone

# Ensure strict UTF-8 console output on Windows
if sys.platform == 'win32':
    sys.stdout.reconfigure(encoding='utf-8')
    sys.stderr.reconfigure(encoding='utf-8')

SDK_ROOT = Path(__file__).resolve().parent.parent
ARCHETYPES_DIR = SDK_ROOT / "project_generator" / "archetypes"

def parse_args():
    parser = argparse.ArgumentParser(description="Synthesize Project Documentation Suite from Sovereign SDK Archetypes.")
    parser.add_argument("--archetype", default="sovereign_dual", help="Archetype ID (e.g., sovereign_dual, web_fullstack)")
    parser.add_argument("--name", default="GrainTrust / RationSafe", help="Project / Application Name")
    parser.add_argument("--target", default=".", help="Target project root directory")
    return parser.parse_args()

def load_archetype(archetype_id: str) -> dict:
    archetype_file = ARCHETYPES_DIR / f"{archetype_id}.json"
    if not archetype_file.exists():
        print(f"[!] Archetype file not found: {archetype_file}. Falling back to sovereign_dual.")
        archetype_file = ARCHETYPES_DIR / "sovereign_dual.json"
    with open(archetype_file, 'r', encoding='utf-8') as f:
        return json.load(f)

def generate_docs(project_name: str, archetype: dict, target_dir: Path):
    docs_dir = target_dir / ".project_docs"
    docs_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(timezone.utc).isoformat()
    
    print(f"[*] Initializing Sovereign Architecture for: {project_name}")
    print(f"[*] Active Archetype: {archetype['name']}")
    print(f"[*] Target Directory: {docs_dir.resolve()}")
    
    # 1. SPEC.md
    spec_content = f"""# {project_name}: Product & System Specification
> **Generated By:** Sovereign AI Governance SDK (Main Supreme Architect)
> **Archetype:** {archetype['name']}
> **Timestamp:** {timestamp}
> **Status:** APPROVED & PLANNING LOCK RELEASED

---

## 1. Executive Summary & Problem Hook
{project_name} is an enterprise-grade sovereign platform engineered to operate reliably under intermittent connectivity, zero-trust security constraints, and strict data privacy regulations.

## 2. Core Functional Invariants
- **Cryptographic Grounding:** {archetype['invariants'].get('cryptography', 'Ed25519')}
- **Data Encryption at Rest:** {archetype['invariants'].get('encryption', 'AES-GCM-256')}
- **Offline Resilience Tier:** {archetype['invariants'].get('offline_engine', 'Local SQLite + IndexedDB')}
- **Central Ledger Engine:** {archetype['invariants'].get('central_db', 'PostgreSQL (Supabase)')}
- **Visual Design Standard:** {archetype['invariants'].get('design_theme', 'GovTech Institutional Palette')}

## 3. Scope Boundaries
- **Phase 1 Prototype:** Core cryptographic transactions, offline local outbox, and zero-knowledge citizen intake.
- **Phase 2 Production:** Realtime WebSocket sync, atomic stored procedures, and automated DAST pentesting.
"""
    with open(docs_dir / "SPEC.md", 'w', encoding='utf-8') as f:
        f.write(spec_content)
    print("  [+] Generated: .project_docs/SPEC.md")

    # 2. ROADMAP.md
    roadmap_content = f"""# {project_name}: Phased Wave Roadmap & Execution Waves
> **Status:** Active Execution Plan
> **Context Budgeting:** Enforced per Wave (Max 250 LOC per atomic commit)

---

## Wave Execution Dependency Graph

```
[Wave 1: Contracts & Types] ──► TypeScript / Dart Domain Interfaces & Zod Schemas
             │
             ▼
[Wave 2: Storage & Cryptography] ──► SQLite + IndexedDB + Ed25519 Signing Engine
             │
             ▼
[Wave 3: Backend API & RLS] ──► Express 5 API + Supabase Migrations & Stored Procedures
             │
             ▼
[Wave 4: UI & Design Tokens] ──► Responsive Dashboard + Mobile Terminal Views
             │
             ▼
[Wave 5: Verification & DAST] ──► Automated 20-Scenario System Tests & Pentest Suite
```

## Milestone Checklist
- [x] Wave 1: Core Type Contracts & Boundary Matrix
- [x] Wave 2: Storage & Asymmetric Signing
- [x] Wave 3: Express API & Supabase RPCs
- [x] Wave 4: Editorial Theme Harmonization
- [x] Wave 5: Strix & ArgosX DAST Validation
"""
    with open(docs_dir / "ROADMAP.md", 'w', encoding='utf-8') as f:
        f.write(roadmap_content)
    print("  [+] Generated: .project_docs/ROADMAP.md")

    # 3. INCIDENT_LOG.md
    incident_content = f"""# {project_name}: Living Incident Journal & Troubleshooting Log
> **Standard:** Prompt-Labeled Entries with Root Cause Analysis (RCA) and Permanent Failsafes

---

## Initial Milestone: Project Initialization
- **Timestamp:** {timestamp}
- **Prompt Reference:** PROMPT-INIT-001
- **Component:** Core Architecture Suite
- **Action Taken:** Bootstrapped project constitution and documentation suite using Sovereign AI Governance SDK.
- **Status:** GREEN / READY FOR ATOMIC EXECUTION
"""
    with open(docs_dir / "INCIDENT_LOG.md", 'w', encoding='utf-8') as f:
        f.write(incident_content)
    print("  [+] Generated: .project_docs/INCIDENT_LOG.md")

    # 4. Initialize .ai_transcripts/ archive directory
    transcripts_dir = target_dir / ".ai_transcripts"
    transcripts_dir.mkdir(parents=True, exist_ok=True)
    with open(transcripts_dir / ".gitkeep", 'w', encoding='utf-8') as f:
        f.write("")
    
    transcripts_readme = f"""# AI Conversation & Trajectory Transcripts
> **Project:** {project_name}  
> **Archiving Engine:** Sovereign SDK Conversation Archiver  
> **Trigger:** Automated Antigravity `Stop` Lifecycle Hook (`.agents/hooks.json`)

## Overview
All conversations with AI agents during the build, audit, and refactor phases are automatically archived here as timestamped Markdown files (`conversation_<id>_<timestamp>.md`).

Each archived transcript captures:
- Exact cleaned user prompts with UTC timestamps
- Complete agent reasoning, plans, and architectural responses
- Expandable logs of every tool call, parameter, and execution result
- Full auditability for git commits, architectural retrospectives, and compliance audits

## Manual Archiving
You can also trigger manual archiving of any active conversation at any time:
```bash
python ./.agents/scripts/archive_conversation.py --conversation-id <CONVERSATION_ID>
```
"""
    with open(transcripts_dir / "README.md", 'w', encoding='utf-8') as f:
        f.write(transcripts_readme)
    print("  [+] Initialized: .ai_transcripts/ (Autonomous Conversation Trajectory Archive)")

    # 5. Initialize .agents/ directory structure (hooks, scripts, rules, skills)
    agents_dir = target_dir / ".agents"
    agents_scripts_dir = agents_dir / "scripts"
    agents_rules_dir = agents_dir / "rules"
    agents_skills_dir = agents_dir / "skills"
    
    agents_scripts_dir.mkdir(parents=True, exist_ok=True)
    agents_rules_dir.mkdir(parents=True, exist_ok=True)
    agents_skills_dir.mkdir(parents=True, exist_ok=True)

    # 5a. Copy template AGENTS.md to project root
    template_agents_md = SDK_ROOT / "templates" / "AGENTS.md"
    if template_agents_md.exists():
        with open(template_agents_md, 'r', encoding='utf-8') as src:
            with open(target_dir / "AGENTS.md", 'w', encoding='utf-8') as dst:
                dst.write(src.read())
        print("  [+] Installed: AGENTS.md (Root Master Control Directives)")

    # 5b. Write .agents/rules/MASTER_CONTROL.md
    rule_content = """# RULE: Sovereign AI Master Control & Constitutional Compliance
> **Scope:** Universal across all conversations and tools  
> **Trigger:** always_on

## Mandatory Directives
1. **Always consult the Sovereign SDK:** All actions must align with `SDK/core_constitution/00_SUPREME_CONSTITUTION.md` and `SDK/MECHANISM.md`.
2. **Empirical Verification Required:** Never conclude a task without executing terminal proof commands (lint, test, build, curl) and printing actual stdout/stderr.
3. **Dispatch to Action Protocols:** For any bug fix, use Protocol 01. For a new feature, use Protocol 02. For refactoring, use Protocol 03. For rollbacks, use Protocol 04. For audits, use Protocol 05. For human feedback, use Protocol 06.
4. **Preserve Conversation Archiver:** Allow the `Stop` lifecycle hook in `.agents/hooks.json` to archive every conversation turn with timestamps to `.ai_transcripts/`.
"""
    with open(agents_rules_dir / "MASTER_CONTROL.md", 'w', encoding='utf-8') as f:
        f.write(rule_content)
    print("  [+] Installed: .agents/rules/MASTER_CONTROL.md")

    # 5c. Copy template hooks.json
    template_hooks = SDK_ROOT / "templates" / "hooks.json"
    if template_hooks.exists():
        with open(template_hooks, 'r', encoding='utf-8') as src:
            with open(agents_dir / "hooks.json", 'w', encoding='utf-8') as dst:
                dst.write(src.read())
        print("  [+] Installed: .agents/hooks.json (Lifecycle Hook Engine)")

    # 5d. Copy template archive_conversation.py
    template_script = SDK_ROOT / "templates" / "scripts" / "archive_conversation.py"
    if template_script.exists():
        with open(template_script, 'r', encoding='utf-8') as src:
            with open(agents_scripts_dir / "archive_conversation.py", 'w', encoding='utf-8') as dst:
                dst.write(src.read())
        print("  [+] Installed: .agents/scripts/archive_conversation.py")

    # 5e. Copy Ready-to-Use Skills from SDK/skills/ into .agents/skills/
    sdk_skills_dir = SDK_ROOT / "skills"
    if sdk_skills_dir.exists():
        import shutil
        for skill_dir in sdk_skills_dir.iterdir():
            if skill_dir.is_dir():
                target_skill = agents_skills_dir / skill_dir.name
                if not target_skill.exists():
                    shutil.copytree(skill_dir, target_skill)
        print("  [+] Installed: 14 Specialized Agent Skills into .agents/skills/")

    # Synthesize starter visual workflow flowchart
    try:
        viz_tool = SDK_ROOT / "tools" / "visualize_project_flow.py"
        if viz_tool.exists():
            import subprocess
            subprocess.run([sys.executable, str(viz_tool), "--project-dir", str(target_dir), "--name", project_name], capture_output=True)
            print("  [+] Synthesized: .project_docs/WORKFLOW_FLOWCHART.html & appmap.yml")
    except Exception as e:
        print(f"  [!] Notice: Flowchart generator deferred: {e}")

    print("\n[SUCCESS] Project Documentation Suite, Master Control & Autonomous Archiver initialized.")
    print("All Department Architects and Action Protocols are active and governing agent execution.")

if __name__ == "__main__":
    args = parse_args()
    arch = load_archetype(args.archetype)
    generate_docs(args.name, arch, Path(args.target))
